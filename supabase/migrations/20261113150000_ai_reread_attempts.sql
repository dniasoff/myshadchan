-- B2a: durable idempotency, single-flight and quota ledger for deliberate
-- resume re-reads. This is additive: the new table starts empty, existing
-- inbox parse attempts and all resume content are untouched.
--
-- Rollback (with Captain/Deploy approval): drop the three new functions,
-- indexes, constraints and ai_reread_attempts. No existing data is changed.

set check_function_bodies = off;

create table public.ai_reread_attempts (
    id bigint generated by default as identity primary key,
    account_id bigint not null,
    resume_id bigint not null,
    request_id uuid not null,
    period text not null,
    status text not null default 'in_progress',
    generation bigint not null default 1,
    result_schema_version smallint not null default 1,
    lease_expires_at timestamp with time zone not null default (now() + interval '5 minutes'),
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint ai_reread_attempts_status_check check (status in ('in_progress', 'completed', 'failed')),
    constraint ai_reread_attempts_period_check check (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    constraint ai_reread_attempts_generation_check check (generation > 0),
    constraint ai_reread_attempts_account_resume_request_key unique (account_id, resume_id, request_id),
    constraint ai_reread_attempts_account_id_fkey foreign key (account_id) references public.accounts(id) on delete cascade,
    constraint ai_reread_attempts_resume_id_fkey foreign key (resume_id) references public.resumes(id) on delete cascade
);

create unique index ai_reread_attempts_resume_in_progress_key
    on public.ai_reread_attempts (resume_id)
    where status = 'in_progress';

comment on table public.ai_reread_attempts is 'Service-role-only idempotency, single-flight and quota ledger for deliberate resume re-reads. No resume content is stored here.';
comment on column public.ai_reread_attempts.result_schema_version is 'The resume sections schema marker written by a completed re-read.';

alter table public.ai_reread_attempts enable row level security;
alter table public.ai_reread_attempts force row level security;

CREATE OR REPLACE FUNCTION public.claim_ai_reread_attempt(p_account_id bigint, p_resume_id bigint, p_request_id uuid, p_current_schema_version smallint)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  c_lease constant interval := interval '5 minutes';
  v_period text := to_char(now(), 'YYYY-MM');
  v_attempt public.ai_reread_attempts;
  v_limit integer;
  v_new_count integer;
  v_reclaim_attempt_id bigint;
begin
  if p_account_id is null or p_resume_id is null or p_request_id is null then
    raise exception 're-read claim requires account, resume and request'
      using errcode = 'invalid_parameter_value';
  end if;

  with doomed as (
    select id
    from public.ai_reread_attempts
    where status in ('completed', 'failed')
      and updated_at < now() - interval '30 days'
    order by updated_at
    limit 100
  )
  delete from public.ai_reread_attempts a
  using doomed
  where a.id = doomed.id;

  perform pg_advisory_xact_lock(
    hashtextextended(format('ai-reread-resume:%s', p_resume_id), 0)
  );

  select * into v_attempt
  from public.ai_reread_attempts
  where account_id = p_account_id
    and resume_id = p_resume_id
    and request_id = p_request_id
  for update;

  if found then
    if v_attempt.status = 'completed' then
      return jsonb_build_object(
        'outcome', 'replayed', 'attempt_id', v_attempt.id,
        'generation', v_attempt.generation
      );
    end if;

    if v_attempt.status = 'in_progress' then
      if v_attempt.lease_expires_at > now() then
        return jsonb_build_object(
          'outcome', 'in_progress', 'attempt_id', v_attempt.id,
          'generation', v_attempt.generation
        );
      end if;
      update public.ai_reread_attempts
      set generation = generation + 1,
          lease_expires_at = now() + c_lease, updated_at = now()
      where id = v_attempt.id
      returning * into v_attempt;
      return jsonb_build_object(
        'outcome', 'reserved', 'attempt_id', v_attempt.id,
        'generation', v_attempt.generation
      );
    end if;

    -- A failed request may be retried with the same idempotency key.  It
    -- keeps its ledger row, but must reserve one new unit before becoming
    -- the next generation; the update below avoids a unique-key insert.
    if v_attempt.status = 'failed' then
      v_reclaim_attempt_id := v_attempt.id;
    end if;
  end if;

  select * into v_attempt
  from public.ai_reread_attempts
  where resume_id = p_resume_id and status = 'in_progress'
  for update;
  if found then
    if v_attempt.account_id = p_account_id
       and v_attempt.lease_expires_at <= now() then
      update public.ai_reread_attempts
      set request_id = p_request_id, generation = generation + 1,
          lease_expires_at = now() + c_lease, updated_at = now()
      where id = v_attempt.id and account_id = p_account_id
      returning * into v_attempt;
      return jsonb_build_object(
        'outcome', 'reserved', 'attempt_id', v_attempt.id,
        'generation', v_attempt.generation
      );
    end if;
    return jsonb_build_object(
      'outcome', 'busy', 'attempt_id', v_attempt.id,
      'generation', v_attempt.generation
    );
  end if;

  v_limit := public.ai_resume_limit_for_account(p_account_id);
  if v_limit <= 0 then
    if exists (
      select 1 from public.subscription
      where account_id = p_account_id and plan = 'ai' and status = 'active'
    ) then
      return jsonb_build_object('outcome', 'no_allowance');
    end if;
    return jsonb_build_object('outcome', 'not_entitled');
  end if;

  insert into public.ai_usage as u (account_id, period, resumes_parsed)
  values (p_account_id, v_period, 1)
  on conflict (account_id, period) do update
    set resumes_parsed = u.resumes_parsed + 1
    where u.resumes_parsed < v_limit
  returning u.resumes_parsed into v_new_count;
  if not found then
    return jsonb_build_object('outcome', 'no_allowance');
  end if;

  if v_reclaim_attempt_id is not null then
    update public.ai_reread_attempts
    set period = v_period, status = 'in_progress', generation = generation + 1,
        lease_expires_at = now() + c_lease, updated_at = now()
    where id = v_reclaim_attempt_id and account_id = p_account_id
      and status = 'failed'
    returning * into v_attempt;
  else
    insert into public.ai_reread_attempts
      (account_id, resume_id, request_id, period, status, generation,
       lease_expires_at, updated_at)
    values
      (p_account_id, p_resume_id, p_request_id, v_period, 'in_progress', 1,
       now() + c_lease, now())
    returning * into v_attempt;
  end if;

  return jsonb_build_object(
    'outcome', 'reserved', 'attempt_id', v_attempt.id,
    'generation', v_attempt.generation
  );
end;
$function$;

CREATE OR REPLACE FUNCTION public.complete_ai_reread_attempt(p_account_id bigint, p_attempt_id bigint, p_generation bigint, p_schema_version smallint)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_generation bigint;
  v_status text;
begin
  update public.ai_reread_attempts
  set status = 'completed', result_schema_version = p_schema_version,
      lease_expires_at = now(), updated_at = now()
  where id = p_attempt_id and account_id = p_account_id
    and status = 'in_progress' and generation = p_generation
  returning generation into v_generation;
  if found then return jsonb_build_object('outcome', 'applied'); end if;

  select generation, status into v_generation, v_status
  from public.ai_reread_attempts
  where id = p_attempt_id and account_id = p_account_id;
  if not found then
    raise exception 'ai_reread_attempts % is not confirmable for account %',
      p_attempt_id, p_account_id;
  end if;
  if v_generation = p_generation and v_status = 'completed' then
    return jsonb_build_object('outcome', 'applied');
  end if;
  return jsonb_build_object('outcome', 'superseded');
end;
$function$;

CREATE OR REPLACE FUNCTION public.release_ai_reread_attempt(p_account_id bigint, p_attempt_id bigint, p_generation bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_period text;
  v_generation bigint;
  v_status text;
begin
  update public.ai_reread_attempts
  set status = 'failed', lease_expires_at = now(), updated_at = now()
  where id = p_attempt_id and account_id = p_account_id
    and status = 'in_progress' and generation = p_generation
  returning period into v_period;
  if found then
    update public.ai_usage
    set resumes_parsed = greatest(resumes_parsed - 1, 0)
    where account_id = p_account_id and period = v_period;
    return jsonb_build_object('outcome', 'applied');
  end if;

  select generation, status into v_generation, v_status
  from public.ai_reread_attempts
  where id = p_attempt_id and account_id = p_account_id;
  if not found then
    raise exception 'ai_reread_attempts % is not releasable for account %',
      p_attempt_id, p_account_id;
  end if;
  if v_generation = p_generation and v_status = 'failed' then
    return jsonb_build_object('outcome', 'applied');
  end if;
  return jsonb_build_object('outcome', 'superseded');
end;
$function$;

-- Keep account deletion safety and tenant export coverage aligned with the
-- declarative schema. The ledger is metadata-only, but must not be silently
-- deleted or omitted from an account export.
CREATE OR REPLACE FUNCTION public.account_is_disposable(p_account_id bigint)
 RETURNS boolean
 LANGUAGE sql
 STABLE
 SET search_path TO ''
AS $function$
  -- Whether an account holds nothing that must outlive it. This is the ONE
  -- data fence behind both halves of the no-orphan invariant: guard_persona_
  -- removal() refuses to archive an account's last active membership unless
  -- this returns true, and dispose_orphaned_account() refuses to delete
  -- unless it does. Sharing the predicate is what makes "delete it, or leave
  -- it reachable" total -- two separately-maintained lists would drift and
  -- leave a state that is neither disposable nor removable.
  --
  -- It is deliberately STRICTER than account_has_domain_data() (which this
  -- calls): that one asks "would a person lose work", which is the right
  -- question for a warning and the wrong one for a DELETE. Every table below
  -- either cascades from accounts -- and so would be destroyed silently -- or
  -- is a cross-account edge whose other side would be left dangling.
  --
  -- Coverage is not maintained by hand: official_demo_account_orphan.sql
  -- derives every account-scoped base table from the catalog and fails if one
  -- is not named in this function's source. A table that deliberately does
  -- NOT block is named here in prose instead, with its reason:
  --   * account_members   -- only ARCHIVED rows remain by the time this is
  --                          consulted; dispose_orphaned_account() deletes them.
  --   * member_state      -- `on delete set null`; dispose repoints it first.
  --   * demo_onboarding_intents -- cascades, so dispose NULLs its account_id
  --                          first to keep the caller's retry state alive.
  --   * demo_clear_receipts -- carries no FK by design; the historical
  --                          root_account_id is the whole point of the ledger.
  --   * demo_run_member_state -- run-scoped and `set null`; a live run is
  --                          already blocked by demo_runs/demo_run_accounts.
  select not (
       public.account_has_domain_data(p_account_id)
    -- Billing and AI entitlement. `subscription` is the server-authoritative
    -- record (accounts.plan is a decoy) -- losing it silently is unacceptable.
    or exists (select 1 from public.subscription where account_id = p_account_id)
    or exists (select 1 from public.ai_usage where account_id = p_account_id)
    or exists (select 1 from public.ai_parse_attempts where account_id = p_account_id)
    or exists (select 1 from public.ai_reread_attempts where account_id = p_account_id)
    or exists (select 1 from public.stripe_events where account_id = p_account_id)
    or exists (select 1 from public.analytics_events where account_id = p_account_id)
    or exists (select 1 from public.account_deletion_requests where account_id = p_account_id)
    -- Content and marketplace surfaces account_has_domain_data does not ask about.
    or exists (select 1 from public.listings where account_id = p_account_id)
    or exists (select 1 from public.listing_withdrawal_locks where account_id = p_account_id)
    or exists (select 1 from public.invites where account_id = p_account_id)
    or exists (select 1 from public.entity_files where account_id = p_account_id)
    or exists (select 1 from public.medical_notes where account_id = p_account_id)
    or exists (select 1 from public.resume_photos where account_id = p_account_id)
    or exists (select 1 from public.single_preferences where account_id = p_account_id)
    or exists (select 1 from public.single_notes where account_id = p_account_id)
    or exists (select 1 from public.share_links where account_id = p_account_id)
    or exists (select 1 from public.trusted_senders where account_id = p_account_id)
    -- Discussion. Private parent-to-parent messages are the most sensitive
    -- rows in the product; they must never be a cascade casualty.
    or exists (select 1 from public.messages where account_id = p_account_id)
    or exists (select 1 from public.threads where account_id = p_account_id)
    or exists (select 1 from public.thread_participants where account_id = p_account_id)
    or exists (select 1 from public.message_notifications where account_id = p_account_id)
    or exists (select 1 from public.task_notifications where account_id = p_account_id)
    -- Cross-account edges: deleting this side would strand the other.
    or exists (
      select 1 from public.connections
      where household_account_id = p_account_id or shadchanus_account_id = p_account_id
    )
    or exists (
      select 1 from public.connection_invites
      where inviter_account_id = p_account_id or accepted_by_account_id = p_account_id
    )
    or exists (
      select 1 from public.child_grants
      where proposer_account_id = p_account_id or grantee_account_id = p_account_id
    )
    -- A live demo lifecycle owns this account's cleanup; never race it.
    or exists (select 1 from public.demo_runs where root_account_id = p_account_id)
    or exists (select 1 from public.demo_run_accounts where account_id = p_account_id)
    or exists (select 1 from public.demo_run_ingest_claims where account_id = p_account_id)
    -- Uploaded bytes. Deleting the row would leave the object unreferenced
    -- and unreachable, which is a leak in the other direction.
    or exists (
      select 1 from storage.objects
      where bucket_id in ('documents', 'entity-files', 'attachments')
        and (name = p_account_id::text or name like p_account_id::text || '/%')
    )
  );
$function$;

CREATE OR REPLACE FUNCTION "public"."export_account_data"() RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  v_account_id bigint := public.current_context_id();
  v_result jsonb := '{}'::jsonb;
begin
  -- Verify an authenticated caller (not service_role). This tested
  -- `current_user = 'postgres'`, which inside a SECURITY DEFINER function
  -- OWNED BY postgres is always true -- so this export, and
  -- export_full_account_bundle which delegates to it, raised
  -- insufficient_privilege for every caller, including the Settings
  -- "download my data" button (PrivacySection.tsx). auth.uid() is the test
  -- every other function here uses and still excludes service_role, which
  -- carries no JWT.
  if auth.uid() is null then
    raise exception 'export_account_data: must be called by authenticated user'
      using errcode = 'insufficient_privilege';
  end if;

  perform public.demo_assert_same_active_run(array[v_account_id], 'account export');

  -- Explicitly list each table to avoid dynamic SQL issues
  -- This is maintainable because schema changes require migrations anyway
  SELECT jsonb_set(v_result, '{accounts}', coalesce(jsonb_agg(to_jsonb(acc)), '[]'))
  FROM public.accounts acc WHERE acc.id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{singles}', coalesce(jsonb_agg(to_jsonb(s)), '[]'))
  FROM public.singles s WHERE s.account_id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{resumes}', coalesce(jsonb_agg(to_jsonb(r)), '[]'))
  FROM public.resumes r WHERE r.account_id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{shidduchim}', coalesce(jsonb_agg(to_jsonb(sh)), '[]'))
  FROM public.shidduchim sh WHERE sh.account_id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{messages}', coalesce(jsonb_agg(to_jsonb(m)), '[]'))
  FROM public.messages m WHERE m.account_id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{references}', coalesce(jsonb_agg(to_jsonb(ref)), '[]'))
  FROM public.references ref WHERE ref.account_id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{tasks}', coalesce(jsonb_agg(to_jsonb(t)), '[]'))
  FROM public.tasks t WHERE t.account_id = v_account_id
  INTO v_result;

  -- `public.notes` has never existed; the real table is single_notes, which
  -- was otherwise absent from this export entirely.
  SELECT jsonb_set(v_result, '{single_notes}', coalesce(jsonb_agg(to_jsonb(n)), '[]'))
  FROM public.single_notes n WHERE n.account_id = v_account_id
  INTO v_result;

  -- `public.events` has never existed either. date_records is the only
  -- account-scoped table it can have meant -- the dates that actually
  -- happened -- and it is real family data, so it is exported under its own
  -- name rather than dropped.
  SELECT jsonb_set(v_result, '{date_records}', coalesce(jsonb_agg(to_jsonb(e)), '[]'))
  FROM public.date_records e WHERE e.account_id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{medical_notes}', coalesce(jsonb_agg(to_jsonb(mn)), '[]'))
  FROM public.medical_notes mn WHERE mn.account_id = v_account_id
  INTO v_result;

  -- connections/connection_invites/child_grants are scoped by their endpoint
  -- columns; none of them has an `account_id`, so each of these selected a
  -- column that does not exist. Predicates match demo_assert_empty_account.
  SELECT jsonb_set(v_result, '{connections}', coalesce(jsonb_agg(to_jsonb(c)), '[]'))
  FROM public.connections c
  WHERE c.household_account_id = v_account_id
     OR c.shadchanus_account_id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{connection_invites}', coalesce(jsonb_agg(to_jsonb(ci)), '[]'))
  FROM public.connection_invites ci
  WHERE ci.inviter_account_id = v_account_id
     OR ci.accepted_by_account_id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{child_grants}', coalesce(jsonb_agg(to_jsonb(cg)), '[]'))
  FROM public.child_grants cg
  WHERE cg.proposer_account_id = v_account_id
     OR cg.grantee_account_id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{share_links}', coalesce(jsonb_agg(to_jsonb(sl)), '[]'))
  FROM public.share_links sl WHERE sl.account_id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{outbound_share_history}', coalesce(jsonb_agg(to_jsonb(osh)), '[]'))
  FROM public.outbound_share_history osh WHERE osh.account_id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{account_members}', coalesce(jsonb_agg(to_jsonb(am)), '[]'))
  FROM public.account_members am WHERE am.account_id = v_account_id
  INTO v_result;

  -- purge_requests is keyed by single_name/single_email and notified_accounts,
  -- not by account_id, so it has no per-account projection; configuration
  -- (id, config) and cron_heartbeat (worker, last_run_at, ...) are global
  -- system tables and never were this customer's data. All three selected a
  -- nonexistent `account_id` column and are dropped rather than guessed at.

  SELECT jsonb_set(v_result, '{account_deletion_requests}', coalesce(jsonb_agg(to_jsonb(dr)), '[]'))
  FROM public.account_deletion_requests dr WHERE dr.account_id = v_account_id
  INTO v_result;

  -- Add remaining tables with account_id column
  SELECT jsonb_set(v_result, '{entity_files}', coalesce(jsonb_agg(to_jsonb(ef)), '[]'))
  FROM public.entity_files ef WHERE ef.account_id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{ai_usage}', coalesce(jsonb_agg(to_jsonb(au)), '[]'))
  FROM public.ai_usage au WHERE au.account_id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{stripe_events}', coalesce(jsonb_agg(to_jsonb(se)), '[]'))
  FROM public.stripe_events se WHERE se.account_id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{ai_parse_attempts}', coalesce(jsonb_agg(to_jsonb(apa)), '[]'))
  FROM public.ai_parse_attempts apa WHERE apa.account_id = v_account_id
  INTO v_result;

  SELECT jsonb_set(v_result, '{ai_reread_attempts}', coalesce(jsonb_agg(to_jsonb(ara)), '[]'))
  FROM public.ai_reread_attempts ara WHERE ara.account_id = v_account_id
  INTO v_result;

  RETURN v_result;
end;
$$;

CREATE OR REPLACE FUNCTION public.get_tenant_tables()
 RETURNS TABLE(table_name text, column_name text)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  return query
  select c.relname::text as table_name, a.attname::text as column_name
  from pg_class c
  join pg_attribute a on a.attrelid = c.oid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and c.relkind = 'r'
    and a.attname = 'account_id'
    and a.attnum > 0
    and not a.attisdropped
    and c.relname not in (
      'subscription', 'ai_usage', 'stripe_events', 'ai_parse_attempts', 'ai_reread_attempts',
      'cron_heartbeat', 'configuration', 'entity_files'
    )
  order by c.relname;
end;
$function$;

