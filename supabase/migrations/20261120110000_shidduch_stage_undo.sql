-- 9ys: keep an auditable stage history so the latest move can be undone by
-- its actor for the short UX window.  The pipeline_transitions graph itself
-- is deliberately unchanged; the trigger exception below is a private,
-- transaction-bound server path for the one reverse write.

create table public.shidduch_stage_transitions (
    id bigint generated by default as identity primary key,
    shidduch_id bigint not null references public.shidduchim(id) on delete cascade,
    account_id bigint not null references public.accounts(id) on delete cascade,
    actor_member_id bigint references public.account_members(id) on delete set null,
    from_state public.pipeline_state not null,
    to_state public.pipeline_state not null,
    previous_close_reason text,
    produced_close_reason text,
    created_at timestamp with time zone not null default clock_timestamp(),
    undone_at timestamp with time zone,
    undo_of_id bigint references public.shidduch_stage_transitions(id) on delete set null
);

comment on table public.shidduch_stage_transitions is
  'Server-owned stage history for transition_shidduch and its short-lived undo path.';

create index shidduch_stage_transitions_latest_idx
  on public.shidduch_stage_transitions (shidduch_id, id desc);

create table public.shidduch_stage_undo_context (
    transaction_id bigint not null,
    shidduch_id bigint not null references public.shidduchim(id) on delete cascade,
    transition_id bigint not null references public.shidduch_stage_transitions(id) on delete cascade,
    actor_member_id bigint references public.account_members(id) on delete set null,
    from_state public.pipeline_state not null,
    to_state public.pipeline_state not null,
    primary key (transaction_id, shidduch_id)
);

comment on table public.shidduch_stage_undo_context is
  'Private, transaction-bound authorization for the one reverse stage update.';

revoke all on table public.shidduch_stage_transitions,
  public.shidduch_stage_undo_context from public, anon, authenticated;

-- The normal graph remains the first and unchanged acceptance branch.  The
-- second branch can only match a row inserted by undo_shidduch() in this
-- transaction; clients have no table privileges and cannot forge its txid.
CREATE OR REPLACE FUNCTION public.enforce_pipeline_transition()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
begin
  if new.pipeline_state is distinct from old.pipeline_state then
    if not exists (
      select 1 from public.pipeline_transitions t
      where t.from_state = old.pipeline_state
        and t.to_state = new.pipeline_state
    ) and not exists (
      select 1
      from public.shidduch_stage_undo_context c
      where c.transaction_id = txid_current()
        and c.shidduch_id = old.id
        and c.from_state = old.pipeline_state
        and c.to_state = new.pipeline_state
    ) then
      raise exception 'illegal pipeline transition: % -> %', old.pipeline_state, new.pipeline_state
        using errcode = 'check_violation';
    end if;
  end if;
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.record_shidduch_stage_transition()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
declare
  v_context public.shidduch_stage_undo_context;
  v_account_id bigint;
  v_member_id bigint;
begin
  if new.pipeline_state is not distinct from old.pipeline_state then
    return new;
  end if;

  select c.* into v_context
  from public.shidduch_stage_undo_context c
  where c.transaction_id = txid_current()
    and c.shidduch_id = old.id;

  v_account_id := public.current_context_id();
  v_member_id := public.current_member_id();

  insert into public.shidduch_stage_transitions (
    shidduch_id,
    account_id,
    actor_member_id,
    from_state,
    to_state,
    previous_close_reason,
    produced_close_reason,
    undo_of_id
  ) values (
    new.id,
    new.account_id,
    v_member_id,
    old.pipeline_state,
    new.pipeline_state,
    old.close_reason,
    new.close_reason,
    case when v_context.transition_id is not null then v_context.transition_id else null end
  );

  return new;
end;
$function$;

create or replace trigger record_shidduch_stage_transition
    after update of pipeline_state on public.shidduchim
    for each row execute function public.record_shidduch_stage_transition();

revoke all on function public.record_shidduch_stage_transition() from public, anon;
grant execute on function public.record_shidduch_stage_transition() to authenticated;
grant execute on function public.record_shidduch_stage_transition() to service_role;

CREATE OR REPLACE FUNCTION public.undo_shidduch(p_id bigint)
RETURNS SETOF public.shidduchim
SECURITY DEFINER
LANGUAGE plpgsql
SET search_path TO ''
AS $function$
declare
  v_account_id bigint;
  v_role text;
  v_member_id bigint;
  v_service_role boolean;
  v_shidduch_account_id bigint;
  v_row public.shidduchim;
  v_transition public.shidduch_stage_transitions;
  v_latest public.shidduch_stage_transitions;
  v_original_id bigint;
begin
  v_service_role := coalesce(auth.role(), '') = 'service_role';
  v_account_id := public.current_context_id();
  v_role := public.current_member_role();
  v_member_id := public.current_member_id();

  -- A missing active context includes anonymous and pending memberships.  The
  -- demo fence is shared with other customer writes: a clearing/expired demo
  -- must not accept a stale browser undo.
  if v_account_id is null
     or not public.demo_storage_write_fence(v_account_id)
     or (not v_service_role and (auth.uid() is null or v_role is null or v_role = 'single')) then
    raise exception 'undo is not available for shidduch %', p_id
      using errcode = 'insufficient_privilege';
  end if;

  select s.account_id into v_shidduch_account_id
  from public.shidduchim s
  where s.id = p_id;

  if not found then
    raise exception 'shidduch % not found', p_id;
  end if;

  -- Parent first, then child: every undo serializes against account deletion
  -- and the transition RPC's shidduch lock in the same order.
  perform 1
  from public.accounts a
  where a.id = v_shidduch_account_id
  for update;

  select s.* into v_row
  from public.shidduchim s
  where s.id = p_id
  for update;

  if not found then
    raise exception 'shidduch % not found', p_id;
  end if;

  -- Re-read the caller and authorization while holding both locks.  This is
  -- intentionally the same owner/accepted-edit-grant/halachic gate as
  -- transition_shidduch(), not a broader "can see the row" check.
  if not v_service_role then
    v_account_id := public.current_context_id();
    v_role := public.current_member_role();
    v_member_id := public.current_member_id();

    if auth.uid() is null or v_account_id is null or v_role is null
       or v_role = 'single'
       or not public.demo_storage_write_fence(v_account_id) then
      raise exception 'undo is not available for shidduch %', p_id
        using errcode = 'insufficient_privilege';
    end if;

    if v_row.account_id is distinct from v_account_id then
      if not exists (
        select 1 from public.child_grants g
        where g.status = 'accepted'
          and g.access_level = 'edit'
          and g.grantee_account_id = v_account_id
          and g.target_single_id = v_row.single_id
      ) or v_row.account_id is distinct from (
        select g.proposer_account_id
        from public.child_grants g
        where g.status = 'accepted'
          and g.access_level = 'edit'
          and g.grantee_account_id = v_account_id
          and g.target_single_id = v_row.single_id
        limit 1
      ) then
        raise exception 'undo is not available for shidduch %', p_id
          using errcode = 'insufficient_privilege';
      end if;
    end if;

    if coalesce(public.shidduch_has_known_halachic_conflict(
      v_row.single_id,
      v_row.person_gender,
      v_row.kohen_status,
      v_row.marital_status
    ), false) then
      raise exception 'undo is not available for shidduch %', p_id
        using errcode = 'insufficient_privilege';
    end if;
  end if;

  -- The latest history row must be this actor's still-live move.  Looking at
  -- the global latest row, rather than merely this actor's latest row, makes a
  -- move by another device or actor stale-safe as well.
  select h.* into v_latest
  from public.shidduch_stage_transitions h
  where h.shidduch_id = p_id
  order by h.id desc
  limit 1
  for update;

  if not found then
    raise exception 'undo is not available for shidduch %', p_id;
  end if;

  -- A repeated request after a completed undo is harmless and returns the
  -- already-restored row.  It never opens a second reverse transition.
  if v_latest.undo_of_id is not null then
    if v_latest.actor_member_id is not distinct from v_member_id then
      return query select * from public.shidduch_row(p_id);
      return;
    end if;
    raise exception 'undo is not available for shidduch %', p_id;
  end if;

  v_transition := v_latest;

  if v_transition.actor_member_id is distinct from v_member_id
     or v_transition.undone_at is not null
     or v_transition.created_at < clock_timestamp() - interval '15 seconds'
     or v_row.pipeline_state is distinct from v_transition.to_state
     or v_row.close_reason is distinct from v_transition.produced_close_reason then
    raise exception 'undo is not available for shidduch %', p_id;
  end if;

  insert into public.shidduch_stage_undo_context (
    transaction_id,
    shidduch_id,
    transition_id,
    actor_member_id,
    from_state,
    to_state
  ) values (
    txid_current(),
    p_id,
    v_transition.id,
    v_member_id,
    v_transition.to_state,
    v_transition.from_state
  );

  update public.shidduchim
  set pipeline_state = v_transition.from_state,
      close_reason = v_transition.previous_close_reason
  where id = p_id
    and pipeline_state = v_transition.to_state
    and close_reason is not distinct from v_transition.produced_close_reason;

  if not found then
    raise exception 'undo is not available for shidduch %', p_id;
  end if;

  update public.shidduch_stage_transitions
  set undone_at = clock_timestamp()
  where id = v_transition.id
    and undone_at is null;

  if not found then
    raise exception 'undo is not available for shidduch %', p_id;
  end if;

  delete from public.shidduch_stage_undo_context
  where transaction_id = txid_current()
    and shidduch_id = p_id;

  return query select * from public.shidduch_row(p_id);
end;
$function$;

revoke all on function public.undo_shidduch(bigint) from public, anon;
grant execute on function public.undo_shidduch(bigint) to authenticated;
grant execute on function public.undo_shidduch(bigint) to service_role;
