-- Unconditional overwrite for a household-kind row (no `is null` guard) —
-- mirrors set_share_link_token_defaults()'s own `new.token` line exactly: a
-- client-supplied value is never honored for a bearer credential. Short
-- token (12 hex chars / 48 bits) on purpose — see 02_functions.sql for the
-- full rationale.
CREATE OR REPLACE FUNCTION public.set_account_inbound_email_token_default()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
begin
  if new.kind = 'household' then
    new.inbound_email_token := encode(extensions.gen_random_bytes(6), 'hex');
  end if;
  return new;
end;
$function$
;

-- Hand-verified against 06_grants.sql (AGENTS.md / 20260803032639's own
-- precedent: `db diff` never re-emits grants correctly for a brand-new
-- table — it emitted verb-by-verb `authenticated`/`service_role` grants with
-- no `revoke` and no sequence privileges at all; replaced here with the
-- exact statements the schema file declares). `anon` never appears in any
-- grant on this table.
revoke all on table public.trusted_senders from anon, authenticated;
grant select, insert, update, delete on table public.trusted_senders to authenticated;
grant all on table public.trusted_senders to service_role;

revoke all on sequence public.trusted_senders_id_seq from anon;
grant usage, select on sequence public.trusted_senders_id_seq to authenticated;
grant all on sequence public.trusted_senders_id_seq to service_role;


