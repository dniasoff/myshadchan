-- Epic 11 (inbound email capture): a private per-household inbound email
-- address on `accounts`, a new `trusted_senders` allowlist table, and a
-- `held` status on `inbox_items` for mail from a sender that is neither a
-- known member nor a trusted address. See supabase/schemas/01_tables.sql,
-- 02_functions.sql, 04_triggers.sql, 05_policies.sql, 06_grants.sql for the
-- declarative source.

-- MANUAL ADJUSTMENT (see AGENTS.md "the empty-table trap"): `db diff`
-- generated the column add and the kind-correspondence CHECK constraint back
-- to back, with no backfill in between. `accounts` already carries
-- production rows (2 accounts, both household-kind, per the pre-flight
-- brief), so validating that CHECK immediately would fail against any of
-- them — invisible locally only because `db reset` seeds against an empty
-- table. Added nullable with no default, backfilled for every existing
-- household-kind row, verified with a fail-closed assertion, and ONLY THEN
-- does the unique index and the CHECK constraint go on.
alter table "public"."accounts" add column "inbound_email_token" extensions.citext;

-- Backfill every existing household-kind account with a fresh CSPRNG token —
-- 6 bytes (48 bits) from pgcrypto, hex-encoded (12 hex chars) — the exact
-- call set_account_inbound_email_token_default() (02_functions.sql) uses for
-- every future row. Short on purpose: this address is displayed to and
-- typed by users, and entropy is not load-bearing here since mail from an
-- unrecognized sender is held for review regardless. shadchanus-kind
-- accounts are left NULL: they have no mailbox of their own.
update "public"."accounts"
set inbound_email_token = encode(extensions.gen_random_bytes(6), 'hex')
where kind = 'household' and inbound_email_token is null;

-- Fail closed rather than let a household row silently keep a NULL token: if
-- the backfill above missed any row, for any reason, abort the whole
-- migration before the unique index/CHECK constraint below ever run — a
-- wrong assumption about the data must stop the deploy, not produce a
-- household account with no inbound address.
do $$
declare
    v_missing bigint;
begin
    select count(*)
      into v_missing
      from public.accounts
     where kind = 'household' and inbound_email_token is null;

    if v_missing > 0 then
        raise exception
            'inbound_email_addresses: % household-kind account(s) still have no inbound_email_token after backfill; refusing to add the unique index/CHECK constraint',
            v_missing;
    end if;
end;
$$;

