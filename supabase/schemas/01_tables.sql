-- forking a parallel table per entity. delivery_channels is in_app+email by
-- default — deliberately no SMS channel (FR44-46).
create table public.tasks (
    id bigint generated by default as identity primary key,
    type text,
    text text,
    due_date timestamp with time zone,
    done_date timestamp with time zone,
    member_id bigint,
    -- Column order here deliberately matches the order `supabase db diff` appends
    -- them (alphabetical), so the declared schema and a migrated database agree
    -- and `db diff` stays quiet. See COLUMN-ORDER TRAP at the top of this file.
    account_id bigint not null,
    delivery_channels text[] not null default array['in_app', 'email']::text[],
    target_id bigint not null,
    target_type text not null default 'shidduch',
    -- Story 8.5 (Task 8, contract §8 rule 4): 'connection' joins the widened
    -- ENTITY_TARGET_TYPES union — R1 (3.14) already lifted `tasks` out of
    -- household-only scope, so a shadchan holding a task about one of their
    -- connections needs no further trigger change, only this value. Review
    -- fix (F2): the comment here used to claim connections rows are never
    -- hard-deleted, so no purge trigger was needed — false (accounts' own
    -- FOR ALL delete policy plus connections' two ON DELETE CASCADE parent
