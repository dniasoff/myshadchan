-- Open signup: carries the 18+ affirmation across a Google OAuth redirect,
-- which signInWithOAuth() cannot put in GoTrue's user_metadata the way the
-- existing email/OTP signup already does (queryParams go to the identity
-- provider, never to Supabase). The frontend inserts one row here, as
-- `anon`, for the exact email address about to authenticate, immediately
-- before redirecting to Google; the signup gate (check_signup_age(),
-- 02_functions.sql) falls back to this table only when user_metadata
-- itself carries no `age_affirmed`, and consumes the matching row in the
-- same statement that finds it.
--
-- No account_id/user_id: unlike every other table in this file, there is
-- no tenant to scope this to yet — the whole point is that no account
-- exists at insert time. Keyed on the email address alone.
--
-- Deliberately insertable by an UNAUTHENTICATED caller (`anon`, see
-- 06_grants.sql/05_policies.sql) — the person creating this row has no
-- session, by construction. That is a real public write surface, and it is
-- safe by design, not by oversight: anyone can insert a row naming an
-- email address they do not control, but doing so grants THEM nothing —
-- the row is only ever consumed by a real Google OAuth flow completing for
-- that exact address, and Google verifies ownership of it before that can
-- happen. A forged intent for an address the inserter does not own can
-- never be redeemed by the inserter; at worst it pre-affirms age for
-- whoever the real owner turns out to be, no differently than that owner
-- ticking the same checkbox themselves. Do not "fix" this by requiring
-- auth — it would defeat the table's entire reason for existing.
--
-- Single-use (check_signup_age() consumes by setting consumed_at, never by
-- matching a row twice) and short-lived (`expires_at` defaults to ten
-- minutes — long enough for the OAuth round trip, short enough that a
-- forgotten tab cannot be replayed hours later). `anon` gets INSERT only,
-- never SELECT (06_grants.sql), so this table can never be used to
-- enumerate which addresses have attempted signup. There is no scheduled-
-- job (pg_cron) infrastructure anywhere in this repo, so expired rows are
-- swept opportunistically by check_signup_age() itself — the one code path
-- that already touches this table on every signup attempt — rather than
-- left to grow forever.
create table public.signup_intents (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    email extensions.citext not null,
    expires_at timestamp with time zone not null default (now() + interval '10 minutes'),
    consumed_at timestamp with time zone
);

create index signup_intents_email_idx on public.signup_intents (email) where consumed_at is null;

