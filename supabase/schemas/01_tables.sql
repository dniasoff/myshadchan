-- Story 9.1: `accounts` is not boilerplate here — a `shadchan` listing has
-- `single_id` null, so without this FK an AD-15 account deletion would
-- orphan a PUBLICLY READABLE row forever (the one table in the product
-- where an orphan is a standing privacy leak, not just dead data). The
-- composite `single_id` FK follows shidduchim_single_id_fkey's precedent
-- above, not inbox_items' FK-less pattern: unlike a capture row, a listing
-- never names a single that does not exist yet. MATCH SIMPLE means a
-- `shadchan` row's null single_id is trivially satisfied, while a `single`
-- row must name a single in the SAME account — closing the cross-tenant id
-- oracle the composite-FK comment block above warns about, and guaranteeing
-- AD-15's per-single purge takes any live listing down with its subject.
alter table public.listings
    add constraint listings_account_id_fkey foreign key (account_id) references public.accounts(id) on delete cascade;
alter table public.listings
    add constraint listings_single_id_fkey
    foreign key (account_id, single_id) references public.singles(account_id, id) on delete cascade;

-- Story 9.3: the composite FK follows the same domain standard as
-- listings_single_id_fkey just above — a purged single (AD-15) takes their
