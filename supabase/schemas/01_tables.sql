-- Photo tab (Story 5.4): one row per uploaded photo of the suggested
-- person, replacing `resumes.photos jsonb` above (dropped in this story —
-- its sole consumer, `Resume.photos?: unknown` in types.ts, and its sole
-- definition here, both go in the same diff; no view, edge function or
-- FakeRest generator ever read it). RLS enforces at ROW granularity, so
-- per-photo visibility (AC-3) requires per-photo rows, not an element
-- inside a whole-row-visible jsonb blob (AD-1). `visibility` reuses
-- shidduchim_visibility_check's vocabulary above, narrowed (the
-- entity_files_visibility_target_check precedent, below) to the two values
-- that mean something for a photo of the suggested person —
-- 'private_single' would hide it from the uploader, who IS the process
-- manager, which is nonsense here. `hidden_at` is a soft-hide (AC-2): a
-- hidden photo is excluded by a plain `hidden_at is null` filter, never
-- deleted (no DELETE code path exists against this table).
create table public.resume_photos (
    id bigint generated by default as identity primary key,
    account_id bigint not null,
    resume_id bigint not null,
    -- `{account_id}/photos/{visibility}/{shidduchim_id}/{uuid}-{filename}` —
    -- the visibility lives in the object key itself (AC-4), because storage
    -- policies can only reason about storage.foldername(name), never about
    -- this row. Consequence: changing visibility after upload is not
    -- supported (hide + re-upload) — there is deliberately no UPDATE policy
    -- to move the object (AC-6).
    path text not null,
    uploaded_at timestamp with time zone not null default now(),
    visibility text not null default 'shared',
    hidden_at timestamp with time zone,
    constraint resume_photos_visibility_check check (
        visibility in ('shared', 'private_parent')
    ),
    -- The two-phase upload's consistency guarantee (entity_files_storage_
    -- path_scope_check precedent, below): account_id is trigger-assigned
    -- from current_context_id(), so if the caller switched context between
    -- the storage PUT and this INSERT, the row is rejected instead of being
    -- written with a path into another account's folder.
    constraint resume_photos_storage_path_scope_check check (
        path like account_id::text || '/%'
    )
);

