-- Stripe webhook idempotency ledger (Story 12.4, AC-3/AC-5). One row per
-- verified Stripe event ever received. The primary key on event_id IS the
-- idempotency mechanism: a duplicate delivery attempts a duplicate INSERT,
-- which fails unique_violation (Postgres 23505, surfaced by PostgREST as
-- HTTP 409). `account_id` is nullable and `on delete set null` — an event
-- for an unknown Stripe customer (no resolvable account) is still recorded,
-- just without a tenant link, and a deleted account must not cascade-delete
-- its own billing history. RLS enabled with ZERO policies (05_policies.sql)
-- — not even SELECT for `authenticated` — because nothing in the product
-- ever needs a client to read raw Stripe event metadata; every access is
-- service_role, from the billing worker alone. New and empty at creation,
-- so — unlike subscription's provisioning_source above — this table needs
-- no backfill.
--
-- `status` (Epic 12 adversarial review, B2 closure): distinguishes
-- "Stripe has delivered this event id" (`'received'`) from "this event was
-- fully, successfully processed" (`'done'`). The original shape of this
-- table let a duplicate INSERT's unique-violation alone answer "deduped,
-- nothing left to do" — which was true only when the FIRST delivery had
-- actually finished. A mutation failure after the row was inserted but
-- before the domain write succeeded left the row behind with nothing
-- recorded about that failure; Stripe's own automatic retry then hit the
-- same primary key and was told the event was already handled, so a
-- transient database error became permanent entitlement drift. Every row
-- is inserted at `'received'` (`claimStripeEvent()`,
-- `workers/billing/resolveAccount.ts`) and moves to `'done'` exactly once,
-- when processing reaches a genuinely terminal outcome (`markStripeEventDone()`)
-- — a mutation applied, a mutation correctly declined as stale, or a
-- legitimate no-op (unresolvable customer, unhandled type, livemode
-- mismatch). A row still at `'received'` on a later delivery of the SAME
-- event id means the earlier attempt never finished, and the Worker
-- reprocesses it rather than deduping past an incomplete attempt.
--
-- COLUMN ORDER: `status` is appended at the physical end (the "COLUMN-ORDER
-- TRAP" header at the top of this file) — it was added by
-- `ALTER TABLE ... ADD COLUMN` after this table's original five, never
-- reordered into a more "logical" position.
create table public.stripe_events (
    event_id text primary key,
    type text not null,
    account_id bigint references public.accounts(id) on delete set null,
    received_at timestamp with time zone not null default now(),
    livemode boolean not null default false,
    status text not null default 'received',
    constraint stripe_events_status_check check (status in ('received', 'done'))
);

-- Per-attachment parse claim/idempotency ledger (Epic 11 Findings 6/7/8
-- closure). One row per (account, inbox item, attachment) ever attempted.
-- Doubles as: (a) the idempotency key that lets a retried POST /parse for
-- the exact same attachment replay a completed result instead of
-- re-invoking the model, and (b) the serialization point that makes
-- ai_usage's monthly-cap increment race-free — claim_ai_parse_attempt()
-- below performs both in one atomic call. Not attached to
-- enforce_household_scope() (04_triggers.sql), matching inbox_items and
-- ai_usage: no source restricts this Worker-internal ledger to household
-- contexts.
create table public.ai_parse_attempts (
    id bigint generated by default as identity primary key,
    account_id bigint not null,
    created_at timestamp with time zone not null default now(),
    inbox_item_id bigint not null,
    attachment_path text not null,
    -- Month key in 'YYYY-MM' form, matching ai_usage.period. Captured at
    -- claim/reclaim time (not recomputed at release time) so a release
    -- after a month boundary rolls back the SAME period's counter it
    -- reserved, never whatever period `now()` resolves to later.
    period text not null,
    status text not null default 'in_progress',
    -- Fencing token (Epic 11 Findings 6/7 review — C2 closure). Bumped by
    -- claim_ai_parse_attempt() every time a NEW generation takes ownership of
    -- this row: a stale reclaim (an abandoned 'in_progress' row) or a reclaim
    -- of a 'failed' row both start a fresh generation. confirm_ai_parse_attempt()
    -- / release_ai_parse_attempt() REQUIRE the caller's own p_generation to
    -- still match the row's current value — a mismatch means a newer
    -- generation already reclaimed this reservation, so the call is a benign
    -- no-op ('superseded') rather than mutating status/ai_usage on the newer
    -- generation's behalf. This is what makes a slow, still-live extractor
    -- request from an older, superseded generation structurally unable to
    -- race a newer generation's own confirm/release — see
    -- claim_ai_parse_attempt()'s own comment for the full argument.
    generation bigint not null default 1,
    started_at timestamp with time zone not null default now(),
    -- The exact POST /parse success payload, cached verbatim for
    -- idempotent replay once status = 'completed'. Null until then.
    result jsonb,
    -- Epic 11 Finding 12 closure. Bumped whenever the POST /parse response
    -- contract changes. claim_ai_parse_attempt() refuses to serve a replay
    -- whose result_schema_version is behind the Worker's own
    -- CURRENT_PARSE_RESULT_SCHEMA_VERSION constant (parsedResumeDraft.ts) —
    -- instead it flips the row back to a free re-claim (same free treatment
    -- as an abandoned in_progress row: the account already paid once for
    -- this document, and a re-parse forced by OUR OWN contract change must
    -- not charge it again). A plain DB column (not a key inside `result`)
    -- so the comparison happens in the SAME atomic statement that decides
    -- the claim outcome, without the Worker fetching-then-deciding.
    result_schema_version smallint not null default 1,
    constraint ai_parse_attempts_status_check check (status in ('in_progress', 'completed', 'failed'))
);

comment on table public.ai_parse_attempts is 'Deliberately excluded from enforce_household_scope() (Story 2.2 AC-4), same open question as public.ai_usage: no source restricts this Worker-internal parse ledger to household contexts.';
comment on column public.ai_parse_attempts.result_schema_version is 'Epic 11 Finding 12 closure: bumped whenever the POST /parse response contract changes. claim_ai_parse_attempt() refuses to serve a replay behind the Worker''s own CURRENT_PARSE_RESULT_SCHEMA_VERSION, flipping the row back to a free re-claim instead.';

