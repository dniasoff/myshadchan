    -- never set or rotate its own household's address. Appended at the
    -- physical TAIL, after `default_thread_visibility` — see the
    -- COLUMN-ORDER TRAP note at the top of this file.
    inbound_email_token extensions.citext,
    -- Story 13.1 (E13-D1 DEFAULT IF SILENT): the household's founding member,
    -- backfilled once from `account_members.invited_by IS NULL` and protected
    -- by a unique index so the derivation's "at most one" hole is closed on the
    -- way in. Nullable because accounts created before this column existed have
    -- no backfill path until the migration runs; the migration backfills and
    -- then the unique index enforces at-most-one going forward.
    founding_member_id bigint,
    constraint accounts_kind_check check (kind in ('household', 'shadchanus')),
    constraint accounts_default_thread_visibility_check check (
        default_thread_visibility in ('open', 'private')
    ),
    -- A household-kind account always has a token; a shadchanus-kind account
    -- never does. Fails loudly if any future path ever produces one without
    -- the other, rather than letting the two silently drift.
    constraint accounts_inbound_email_token_kind_check check (
        (kind = 'household') = (inbound_email_token is not null)
    )
